// Helper function to get equation by slug
export function getEquationBySlug(slug: string): EquationData | undefined {
  return equationsData.find(eq => eq.slug === slug);
}

// Helper function to get all equation slugs (for sitemap and static generation)
export function getAllEquationSlugs(): string[] {
  return equationsData.map(eq => eq.slug);
}

// Helper function to convert equation to URL-friendly slug
export function equationToSlug(equation: string): string {
  return equation
    .toLowerCase()
    .replace(/\s+/g, '-')
    .replace(/\+/g, '-plus-')
    .replace(/-/g, '-minus-')
    .replace(/=/g, '-equals-')
    .replace(/\//g, '-divided-by-')
    .replace(/\*/g, '-times-')
    .replace(/\(/g, '-parenthesis-')
    .replace(/\)/g, '-parenthesis-')
    .replace(/[^a-z0-9-]/g, '');
}
